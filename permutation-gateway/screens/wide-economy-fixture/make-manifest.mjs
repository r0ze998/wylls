// One-shot generator of ./manifest.mjs: the SHA-256 of each of the 40 original wide-economy fixture files.
//
//   node --import ./scripts/ci/no-keys-guard.mjs permutation-gateway/screens/wide-economy-fixture/make-manifest.mjs
//
// manifest.mjs is already committed, so this is NOT a setup step. Strict by construction: NO argument is accepted; it
// reads exactly the 40 allowlisted originals under the fixed fixture directory, requires each to be a regular file
// inside it, and creates exactly one new file, manifest.mjs, next to itself, with exclusive create (O_CREAT|O_EXCL, flag
// 'wx'): anything already at that path, a file, a symlink (even a dangling one) or a directory, makes it fail with
// nothing followed and nothing modified. There is deliberately no overwrite mode and no deletion code: replacing the
// manifest on purpose is a separately reviewed task. It hashes with node:crypto, deliberately NOT the SDK sha256 that model.mjs uses, so the pins and
// the check are two implementations. It does not import model.mjs (which imports the manifest it writes).
//
// The pins identify WHICH checked-in files these are. They are not chain provenance, not a replay, not a signature.
import { createHash } from 'node:crypto';
import { readFile, realpath, lstat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '..', '..', '..');
const BIN_ROOT = join(REPO_ROOT, 'frontier-node', 'crates', 'verify', 'tests', 'fixtures', 'wide_economy');
const OUT = join(HERE, 'manifest.mjs');
const CASES = ['harvest', 'building', 'wall', 'tier', 'train'];
const FILES = ['season.bin', 'citizen_pre.bin', 'holding_pre.bin', 'province_pre.bin',
  'citizen_post.bin', 'holding_post.bin', 'province_post.bin', 'record.bin'];

if (process.argv.length > 2) {
  process.stderr.write('usage: make-manifest.mjs   (no argument is accepted)\n');
  process.exit(2);
}

const realRoot = await realpath(BIN_ROOT);
const pins = {};
for (const name of CASES) {
  pins[name] = {};
  for (const file of FILES) {
    const path = join(BIN_ROOT, name, file);
    const info = await lstat(path);
    if (!info.isFile()) throw new Error(`${name}/${file}: not a regular file`);
    const real = await realpath(path);
    if (!real.startsWith(realRoot + sep)) throw new Error(`${name}/${file}: escapes the fixture directory`);
    pins[name][file] = createHash('sha256').update(await readFile(real)).digest('hex');
  }
}

const lines = CASES.map(name => `  ${name}: Object.freeze({\n${FILES.map(f => `    '${f}': '${pins[name][f]}',`).join('\n')}\n  }),`);
const source = `// GENERATED by make-manifest.mjs from the 40 original files under frontier-node/crates/verify/tests/fixtures/wide_economy/.
// SHA-256 pins: they identify which checked-in fixture files these are. They are not chain provenance, not a replay,
// and not a proof that the host run was honest. Any replacement is a separately reviewed change, never a setup step.
export const MANIFEST = Object.freeze({
${lines.join('\n')}
});
`;

try {
  await writeFile(OUT, source, { encoding: 'utf8', flag: 'wx', mode: 0o644 });
} catch (e) {
  if (e?.code === 'EEXIST') {
    process.stderr.write('manifest.mjs already exists; refusing to touch it (replacement is a separately reviewed task)\n');
    process.exit(1);
  }
  throw e;
}
process.stdout.write(`wrote ${OUT} (${CASES.length * FILES.length} pins)\n`);
