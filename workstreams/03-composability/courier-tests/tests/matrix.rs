//! Workstream 03: the instruction table, generated from the ABI itself
//! (`frontier_abi::v2`: tags, account lists, budgets, data lengths) and the
//! core harness's (instruction, error code) coverage registry
//! (`permutation_frontier_svm_tests::cover::covered_by`), so the table
//! cannot drift from the code it describes.
//!
//! **Execution:** `[NO CHAIN: table generation]`. With
//! `WS03_MATRIX_OUT=<file>` it writes the Markdown table; without, it only
//! checks the facts the hand-written documents rely on.

use frontier_abi::prologue::{Acc, Wr};
use frontier_abi::v2::budgets::{cu_limit_s1, loaded_limit_s1};
use frontier_abi::v2::ix::data_len_range;
use frontier_abi::v2::prologue::accounts_of;
use frontier_abi::v2::tags::{relay_player_shape, relay_settle_shape};
use frontier_abi::v2::Ix;
use permutation_frontier_svm_tests::cover::{covered_by, Code, Cover};

fn acc(a: Acc) -> String {
    match a {
        Acc::Kind(k) => format!("{k:?}"),
        Acc::KindV2(k) => format!("{k:?}"),
        Acc::Either(a, b) => format!("{a:?}\\|{b:?}"),
        Acc::EitherV2(a, b) => format!("{a:?}\\|{b:?}"),
        other => format!("{other:?}"),
    }
}

fn wr(w: Wr) -> &'static str {
    match w {
        Wr::R => "r",
        Wr::W => "w",
        Wr::Either => "r\\|w",
    }
}

/// `name:Kind[s][w]` per position; a repeated group as `(…)×min..max`.
fn accounts(ix: Ix) -> String {
    let mut out = vec![];
    for g in accounts_of(ix) {
        let specs: Vec<String> = g
            .specs
            .iter()
            .map(|s| {
                format!(
                    "{}:{}{}{}",
                    s.name,
                    acc(s.acc),
                    if s.signer { " s" } else { "" },
                    match s.wr {
                        Wr::R => String::new(),
                        w => format!(" {}", wr(w)),
                    }
                )
            })
            .collect();
        if g.min == 1 && g.max == 1 {
            out.extend(specs);
        } else {
            out.push(format!("({})×{}..{}", specs.join(", "), g.min, g.max));
        }
    }
    out.join(", ")
}

fn signers(ix: Ix) -> String {
    let v: Vec<&str> = accounts_of(ix)
        .iter()
        .flat_map(|g| g.specs.iter())
        .filter(|s| s.signer)
        .map(|s| s.name)
        .collect();
    v.join(", ")
}

fn codes(ix: Ix) -> String {
    let mut v: Vec<String> = vec![];
    for c in covered_by(ix) {
        match c {
            Cover::Test(_, cs) => {
                for code in cs.iter() {
                    let s = match code {
                        Code::Err(e) => e.name().to_string(),
                        Code::Cq(e) => e.name().to_string(),
                        _ => continue,
                    };
                    if !v.contains(&s) {
                        v.push(s);
                    }
                }
            }
            Cover::Pending(u) => v.push(format!("(pending: {u})")),
        }
    }
    v.join(", ")
}

#[test]
fn matrix_generate() {
    // Facts the documents state.
    assert!(!Ix::SendCaravan.top_level_only());
    assert!(relay_player_shape(Ix::SendCaravan));
    let top: Vec<&str> = Ix::ALL
        .iter()
        .filter(|i| i.top_level_only())
        .map(|i| i.name())
        .collect();
    assert_eq!(
        top,
        [
            "ConsumeGenesisSeed",
            "PostAnchor",
            "PostAnchorMulti",
            "PostSeed",
            "PostBeacon",
            "ConsumeRingSeed",
            "OpenProvince",
            "Reveal",
            "GatherClash",
            "ResolveFromInputs",
            "ResolveClash",
            "SkipQuiet",
            "FastForward"
        ]
    );
    let Ok(out) = std::env::var("WS03_MATRIX_OUT") else {
        return;
    };
    let mut md = String::new();
    md.push_str("<!-- generated by workstreams/03-composability/courier-tests/tests/matrix.rs (WS03_MATRIX_OUT); do not edit -->\n");
    md.push_str("# 全命令の一覧（ABIから生成）\n\n");
    md.push_str("ABI v2 の全 74 命令。`frontier_abi::v2` の表（タグ、keeper class、`top_level_only`、relay の shape、口座の並び、S1 の CU 上限と `L(kind)`、データ長）と、コアの svm-tests が実際に検査しているエラー（`cover::covered_by`）から生成した。\n\n");
    md.push_str("- 口座: `名前:種類`、`s` は署名者、`w` は書込、`r|w` は命令が決める。無印は読取。`(…)×a..b` は繰返し。\n");
    md.push_str("- `CPI拒否` が「なし」でも CPI で動くとは限らない（[02-instruction-matrix.ja.md](../02-instruction-matrix.ja.md) の注意を参照）。実チェーン（LiteSVM）で CPI を確かめたのは SendCaravan だけ。\n");
    md.push_str("- 「コアのテストが検査するエラー」は網羅ではない。どの player 命令にも前置き（prologue）の Auth / SessionExpired / Bucket / WrongStatus / RulesetMismatch / BadAddress / BadAccount / TooManyAccounts が加わる。\n\n");
    md.push_str("| tag | 命令 | class | CPI拒否 | relay | 署名者 | 口座 | データ長 | CU上限(S1) | L(kind)(S1) | コアのテストが検査するエラー |\n|---|---|---|---|---|---|---|---|---|---|---|\n");
    for ix in Ix::ALL {
        let (lo, hi) = data_len_range(*ix);
        let relay = if relay_player_shape(*ix) {
            "player"
        } else if relay_settle_shape(*ix) {
            "settle"
        } else {
            "—"
        };
        md.push_str(&format!(
            "| 0x{:02X} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |\n",
            ix.tag(),
            ix.name(),
            ix.class().name(),
            if ix.top_level_only() {
                "**あり**"
            } else {
                "なし"
            },
            relay,
            signers(*ix),
            accounts(*ix),
            if lo == hi {
                lo.to_string()
            } else {
                format!("{lo}–{hi}")
            },
            cu_limit_s1(*ix),
            loaded_limit_s1(*ix),
            codes(*ix),
        ));
    }
    std::fs::write(out, md).unwrap();
}
