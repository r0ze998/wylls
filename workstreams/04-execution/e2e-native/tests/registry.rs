//! The contract registry (workstream 04, one place for the numbers): every
//! ABI v2 instruction tag of the game program, the prize program's tags,
//! the program / rules versions and ruleset hashes, the sizes of the
//! accounts runs touch, the amount units. Rendered from the code itself and
//! compared with the committed `../contracts/registry.txt`: when the code
//! changes a number, this test fails until the registry is regenerated
//! (`REGEN=1 cargo test --test registry`) and the change is reviewed. Other
//! workstreams read the registry and never fix a number of their own.

use frontier_abi::v2::layout::player::{citizen, holding};
use frontier_abi::v2::layout::s1::{caravan, vault};
use frontier_abi::v2::layout::world::season;
use frontier_abi::v2::presets as v2p;
use frontier_abi::v2::tags::Ix;

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn render() -> String {
    let mut s = String::new();
    s.push_str("# Wylls contract registry (generated by workstreams/04-execution/e2e-native/tests/registry.rs; do not edit by hand)\n");
    s.push_str("\n[versions]\n");
    s.push_str(&format!(
        "program_version_v2 = {}\n",
        v2p::PROGRAM_VERSION_V2
    ));
    s.push_str(&format!(
        "program_version_s1 = {}\n",
        v2p::PROGRAM_VERSION_S1
    ));
    s.push_str(&format!("rules_version_v2 = {}\n", v2p::RULES_VERSION_V2));
    s.push_str(&format!("rules_version_s1 = {}\n", v2p::RULES_VERSION_S1));
    s.push_str(&format!(
        "ruleset_hash_v2 = {}\n",
        hex(&v2p::RULESET_HASH_V2)
    ));
    s.push_str(&format!(
        "ruleset_hash_v3 = {}\n",
        hex(&v2p::RULESET_HASH_V3)
    ));
    s.push_str("\n[world]\n");
    s.push_str(&format!(
        "world_account = Season PDA [{:?}, le64(id)] under the game program; every game account = sha256(world_account || seed || program)\n",
        String::from_utf8_lossy(season::PDA_PREFIX)
    ));
    s.push_str(&format!(
        "season_size = {}\nseason_tombstone_size = {}\n",
        season::SIZE,
        season::TOMBSTONE_SIZE
    ));
    s.push_str(&format!(
        "season_status = created {} announced {} seeded {} running {} ended {} closed {} aborted {}\n",
        season::STATUS_CREATED,
        season::STATUS_ANNOUNCED,
        season::STATUS_SEEDED,
        season::STATUS_RUNNING,
        season::STATUS_ENDED,
        season::STATUS_CLOSED,
        season::STATUS_ABORTED
    ));
    s.push_str("\n[accounts]\n");
    s.push_str(&format!("citizen = {} bytes\n", citizen::SIZE));
    s.push_str(&format!("holding = {} bytes\n", holding::SIZE));
    s.push_str(&format!("vault = {} bytes\n", vault::SIZE));
    s.push_str(&format!("caravan = {} bytes\n", caravan::SIZE));
    s.push_str(&format!(
        "prize_pool = {} bytes\n",
        permutation_prize::pool::SIZE
    ));
    s.push_str("\n[units]\n");
    s.push_str(&format!("resource = milli-units i64 on chain (MILLI = {}); logs carry whole units u32, rounded down (cargo_log)\n", permutation_rules::fixed::MILLI));
    s.push_str("test_usdc = 6 decimals (prize pool DECIMALS from the mint)\n");
    s.push_str("bell = u32 index of bell_secs seconds since genesis_ts\n");
    s.push_str("\n[game_program_ix_v2] # tag name class top_level_only\n");
    for ix in Ix::ALL {
        s.push_str(&format!(
            "0x{:02x} {} {:?} {}\n",
            ix.tag(),
            ix.name(),
            ix.class(),
            ix.top_level_only()
        ));
    }
    s.push_str("\n[prize_program_ix] # legacy season pool (compatibility only)\n");
    use permutation_prize::tag as t;
    for (n, v) in [
        ("InitPool", t::INIT_POOL),
        ("Pay", t::PAY),
        ("Tally", t::TALLY),
        ("Finalize", t::FINALIZE),
        ("SetShares", t::SET_SHARES),
        ("Claim", t::CLAIM),
        ("WithdrawOps", t::WITHDRAW_OPS),
    ] {
        s.push_str(&format!("{v} {n}\n"));
    }
    s
}

#[test]
fn registry_matches_the_code() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../contracts/registry.txt");
    let now = render();
    if std::env::var("REGEN").is_ok() {
        std::fs::create_dir_all(concat!(env!("CARGO_MANIFEST_DIR"), "/../contracts")).unwrap();
        std::fs::write(path, &now).unwrap();
    }
    let committed = std::fs::read_to_string(path).unwrap_or_default();
    assert!(
        committed == now,
        "the code's numbers differ from contracts/registry.txt; regenerate with REGEN=1 and review the diff"
    );
}
