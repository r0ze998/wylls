#!/usr/bin/env python3
"""Writes the core copy of the custody kernel.

The kernel lives in workstreams/10-custody/custody/src/{lot,layout}.rs (one
source of truth, tested there). patches/0001 carries it into
permutation-rules as `src/frontier/custody.rs`: this script makes that file
from the two sources, only rewriting paths. `--check FILE` compares instead
of writing (run.sh uses it so the patch cannot drift from the tested code).

usage: core-kernel.py OUT            write OUT
       core-kernel.py --check FILE   exit 1 if FILE differs
"""
import pathlib
import sys

here = pathlib.Path(__file__).resolve().parent.parent / "custody" / "src"
lot = (here / "lot.rs").read_text()
layout = (here / "layout.rs").read_text()

lot = lot.replace("use permutation_rules::fixed::MILLI;", "use crate::fixed::MILLI;")
lot = lot.replace(
    "use permutation_rules::frontier::holding::{Resource, RESOURCES};",
    "use super::holding::{Resource, RESOURCES};",
)
lot = lot.replace("[`crate::layout::lot`]", "[`layout::lot`]")
assert "permutation_rules" not in lot, "unhandled path in lot.rs"

layout = layout.replace(
    "use crate::lot::{Inbound, Lot, Order, PlaceRef, MAX_INBOUND, MAX_ORDERS};",
    "use super::{Inbound, Lot, Order, PlaceRef, MAX_INBOUND, MAX_ORDERS};",
)
layout = layout.replace("    use crate::lot::*;", "    use super::super::*;")
assert "crate::lot" not in layout, "unhandled path in layout.rs"

head = (
    "// Generated by workstreams/10-custody/scripts/core-kernel.py from\n"
    "// workstreams/10-custody/custody/src/{lot,layout}.rs; edit those.\n\n"
)
body = head + lot.rstrip() + "\n\npub mod layout {\n"
body += "".join(("    " + l if l.strip() else l) for l in layout.splitlines(True))
body += "}\n"

import subprocess
import tempfile

# rustfmt the result, as the core's CI checks its formatting.
with tempfile.NamedTemporaryFile("w", suffix=".rs", delete=False) as t:
    t.write(body)
subprocess.run(["rustfmt", "--edition", "2021", t.name], check=True)
body = pathlib.Path(t.name).read_text()
pathlib.Path(t.name).unlink()

if sys.argv[1] == "--check":
    have = pathlib.Path(sys.argv[2]).read_text()
    if have != body:
        sys.exit(f"{sys.argv[2]} differs from the workstream kernel; regenerate it")
else:
    pathlib.Path(sys.argv[1]).write_text(body)
